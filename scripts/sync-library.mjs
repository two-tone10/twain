// Turns an export from the Keep library portal into src/keep/library.mjs.
//   node scripts/sync-library.mjs path/to/export.json     (the portal's "Copy JSON")
//   node scripts/sync-library.mjs path/to/pulled/moments  (a folder of one-JSON-per-moment, as Claude pulls it)
// Each moment is { t, k, d } (text, why, deck); rows with off: true are skipped.
// Duplicates within a deck are dropped and anything with an unknown why or deck is reported and left out.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { WHYS, DECKS } from '../src/keep/content.mjs';

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/sync-library.mjs export.json'); process.exit(1); }
const read = (f) => JSON.parse(readFileSync(f, 'utf8'));
let rows;
if (statSync(src).isDirectory()) rows = readdirSync(src).filter((f) => f.endsWith('.json')).map((f) => read(join(src, f))).map((r) => r.data ?? r);
else { const raw = read(src); rows = Array.isArray(raw) ? raw : raw.moments; }

const whys = WHYS.map((w) => w.key), decks = DECKS.map((d) => d.key);
const seen = new Set(), out = [], bad = [];
for (const r of rows) {
  if (r.off) continue;
  const t = String(r.t ?? '').replace(/\s+/g, ' ').replace(/'/g, '’').trim();
  if (!t || !whys.includes(r.k) || !decks.includes(r.d)) { bad.push(r); continue; }
  const id = `${r.d}|${t.toLowerCase()}`;
  if (seen.has(id)) continue;
  seen.add(id);
  out.push({ t, k: r.k, d: r.d });
}
out.sort((a, b) => decks.indexOf(a.d) - decks.indexOf(b.d) || whys.indexOf(a.k) - whys.indexOf(b.k) || a.t.localeCompare(b.t));

const body = out.map((m) => `  ${JSON.stringify(m)},`).join('\n');
const file = `// Every moment that can fall. Generated by scripts/sync-library.mjs from the library portal; edit there, not here.
// t: what falls, k: its why, d: the deck it belongs to.
export const LIBRARY = [
${body}
];
`;
writeFileSync(fileURLToPath(new URL('../src/keep/library.mjs', import.meta.url)), file);
const counts = {};
for (const m of out) counts[m.d] = (counts[m.d] || 0) + 1;
console.log(`${out.length} moments`, counts);
if (bad.length) console.log(`skipped ${bad.length} with an unknown why or deck:`, bad);
